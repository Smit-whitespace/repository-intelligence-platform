"""Edit proposals: reviewable, server-stored changes.

A proposal is built from search/replace operations, whether an agent
supplies them over MCP or RIP's edit model generates them. It is stored
in the project (``.local_openclaw/proposals/``) and applied later *by
id*, so what a person reviewed is exactly what gets written. Clients
never send file contents at apply time.

Search/replace is used instead of whole files or unified diffs because
it is what models reliably produce: an exact snippet to find (which must
match exactly once) and its replacement. Mistakes are reported precisely,
per operation, so the author can fix them.
"""

import difflib
import re
from datetime import UTC, datetime
from enum import StrEnum
from pathlib import Path
from uuid import uuid4

from pydantic import BaseModel, Field, ValidationError

from app.core.storage.exceptions import (
    StorageError,
    StorageResourceNotFoundError,
)
from app.core.storage.filesystem import FileSystemStorage
from app.core.storage.integrity import sign, verify
from app.core.storage.locations import project_storage_directory
from app.editing.change_applier import (
    ChangeApplier,
    read_text_for_edit,
)
from app.editing.exceptions import (
    EditingError,
    ProposalNotFoundError,
    UntrustedStateError,
)
from app.editing.models import (
    ChangeSet,
    FileEdit,
)
from app.editing.validation import ValidationReport

MAX_OPERATIONS = 50

_PROPOSALS_DIRECTORY = Path("proposals")

_PROPOSAL_ID_PATTERN = re.compile(
    r"[0-9a-f]{32}",
)


class EditOperation(BaseModel):
    """Replace one exact snippet of a file, or create a file."""

    path: str = Field(
        min_length=1,
        description="Repository-relative file path.",
        examples=[
            "backend/app/main.py",
        ],
    )

    search: str = Field(
        default="",
        description="Exact existing text to replace; it must occur exactly "
        "once in the file. Empty to create a new file.",
    )

    replace: str = Field(
        description="Text to put in its place (the whole content for a new "
        "file).",
    )


class ProposalStatus(StrEnum):
    """Lifecycle of a proposal."""

    PENDING = "pending"

    APPLIED = "applied"

    REJECTED = "rejected"

    ROLLED_BACK = "rolled_back"


class ProposalSource(StrEnum):
    """Who wrote the edits."""

    CLIENT = "client"
    """Operations supplied by a client, such as an agent over MCP."""

    PLANNER = "planner"
    """Generated by RIP's edit model from an instruction."""


class FileChange(StrEnum):
    """What a proposal does to one file."""

    CREATE = "create"

    MODIFY = "modify"


class ProposedFile(BaseModel):
    """The proposed change to one file."""

    path: str

    change: FileChange

    added_lines: int

    removed_lines: int

    diff: str


class EditProposalView(BaseModel):
    """A proposal as shown to people and clients (no full file bodies)."""

    proposal_id: str

    created_at: datetime

    updated_at: datetime

    status: ProposalStatus

    source: ProposalSource

    description: str

    model: str | None = Field(
        default=None,
        description="provider/model that generated the edits (planner only).",
    )

    notes: str | None = Field(
        default=None,
        description="The edit model's explanation, if it gave one.",
    )

    files: list[ProposedFile]

    diff: str = Field(
        description="Unified diff of the whole proposal.",
    )

    snapshot_id: str | None = Field(
        default=None,
        description="Snapshot for rolling back, once applied.",
    )

    validation: ValidationReport | None = None


class EditProposal(EditProposalView):
    """A stored proposal, including the exact contents to write."""

    change_set: ChangeSet

    def view(
        self,
    ) -> EditProposalView:
        return EditProposalView.model_validate(
            self.model_dump(
                exclude={
                    "change_set",
                },
            ),
        )


class EditProposalError(EditingError):
    """Operations could not be turned into a proposal (HTTP 400).

    The message lists every problem, one per line, so the author can fix
    them all in one go.
    """


def build_proposal(
    repository_root: Path,
    operations: list[EditOperation],
    description: str,
    source: ProposalSource,
    change_applier: ChangeApplier,
    model: str | None = None,
    notes: str | None = None,
) -> EditProposal:
    """Turn search/replace operations into a proposal.

    Paths are validated (inside the root, not protected) before any file
    is read. Operations on the same file apply in order.
    """

    if not operations:
        raise EditProposalError(
            "No edit operations were given.",
        )

    if len(operations) > MAX_OPERATIONS:
        raise EditProposalError(
            f"At most {MAX_OPERATIONS} operations per proposal.",
        )

    root = repository_root.resolve()

    operations_by_path: dict[str, list[EditOperation]] = {}

    for operation in operations:
        normalized = Path(
            operation.path.replace(
                "\\",
                "/",
            ),
        ).as_posix()

        operations_by_path.setdefault(
            normalized,
            [],
        ).append(
            operation,
        )

    # Validate every path before reading anything.
    change_applier.validate_change_set(
        repository_root=root,
        change_set=ChangeSet(
            edits=[
                FileEdit(
                    relative_path=Path(
                        path,
                    ),
                    original_content="",
                    updated_content="",
                )
                for path in operations_by_path
            ],
        ),
    )

    errors: list[str] = []

    edits: list[FileEdit] = []

    files: list[ProposedFile] = []

    for path, path_operations in operations_by_path.items():
        current = read_text_for_edit(
            (root / path).resolve(),
            Path(
                path,
            ),
        )

        content = current

        for index, operation in enumerate(
            path_operations,
            start=1,
        ):
            content, error = _apply_operation(
                path,
                content,
                operation,
            )

            if error:
                errors.append(
                    f"{path} (operation {index}): {error}",
                )

                break

        if content is None or content == current:
            continue

        edits.append(
            FileEdit(
                relative_path=Path(
                    path,
                ),
                original_content=current or "",
                updated_content=content,
            ),
        )

        files.append(
            _proposed_file(
                path,
                current,
                content,
            ),
        )

    if errors:
        raise EditProposalError(
            "\n".join(
                errors,
            ),
        )

    if not edits:
        raise EditProposalError(
            "The operations do not change any file.",
        )

    now = datetime.now(
        UTC,
    )

    return EditProposal(
        proposal_id=uuid4().hex,
        created_at=now,
        updated_at=now,
        status=ProposalStatus.PENDING,
        source=source,
        description=description,
        model=model,
        notes=notes,
        files=files,
        diff="".join(
            file.diff
            for file in files
        ),
        change_set=ChangeSet(
            edits=edits,
        ),
    )


def _apply_operation(
    path: str,
    content: str | None,
    operation: EditOperation,
) -> tuple[str | None, str | None]:
    """Apply one operation; return (new content, error or None)."""

    if operation.search == "":
        if content:
            return content, (
                "the file already exists; put the exact text to replace in "
                "'search'"
            )

        return operation.replace, None

    if content is None:
        return content, (
            "the file does not exist; use an empty 'search' to create it"
        )

    search = operation.search

    replace = operation.replace

    matches = _find_matches(
        content,
        search,
    )

    # Models usually write "\n"; let that match a CRLF file.
    if not matches and "\r\n" in content and "\r\n" not in search:
        crlf_search = search.replace(
            "\n",
            "\r\n",
        )

        crlf_matches = _find_matches(
            content,
            crlf_search,
        )

        if crlf_matches:
            search = crlf_search

            matches = crlf_matches

    if not matches:
        if search in content:
            return content, (
                "'search' spans several lines but matches only part of a "
                "line; copy whole lines, including their indentation"
            )

        return content, (
            "'search' text was not found; copy it exactly from the current "
            "file, including indentation"
        )

    if len(matches) > 1:
        return content, (
            f"'search' text occurs {len(matches)} times; include more "
            "surrounding lines so it occurs exactly once"
        )

    # Keep the file's line endings: a CRLF file stays CRLF.
    if "\r\n" in content and "\r\n" not in replace:
        replace = replace.replace(
            "\n",
            "\r\n",
        )

    start = matches[0]

    return content[:start] + replace + content[start + len(search) :], None


def _find_matches(
    content: str,
    search: str,
) -> list[int]:
    """Return the start of every acceptable match of ``search``.

    A search containing a line break is line-based: it must start at the
    beginning of a line and end at the end of one. Otherwise
    ``"  return x\n"`` would match inside ``"    return x\n"`` and quietly
    break its indentation. A search without a line break may match
    within a line (renaming an identifier, say).
    """

    whole_lines = "\n" in search

    matches: list[int] = []

    start = content.find(
        search,
    )

    while start != -1:
        end = start + len(search)

        if not whole_lines or (
            (start == 0 or content[start - 1] == "\n")
            and (
                search.endswith("\n")
                or end == len(content)
                or content[end] in "\r\n"
            )
        ):
            matches.append(
                start,
            )

        start = content.find(
            search,
            start + 1,
        )

    return matches


def _proposed_file(
    path: str,
    original: str | None,
    updated: str,
) -> ProposedFile:
    diff = unified_diff(
        path,
        original,
        updated,
    )

    added = removed = 0

    # The first two lines are the ---/+++ file headers; a removed SQL
    # comment ("-- x") later shows as "--- x" and must still count.
    for line in diff.splitlines()[2:]:
        if line.startswith("+"):
            added += 1

        elif line.startswith("-"):
            removed += 1

    return ProposedFile(
        path=path,
        change=(
            FileChange.CREATE
            if original is None
            else FileChange.MODIFY
        ),
        added_lines=added,
        removed_lines=removed,
        diff=diff,
    )


def unified_diff(
    path: str,
    original: str | None,
    updated: str,
) -> str:
    """Return a git-style unified diff for one file."""

    lines = difflib.unified_diff(
        _lines(
            original or "",
        ),
        _lines(
            updated,
        ),
        fromfile="/dev/null" if original is None else f"a/{path}",
        tofile=f"b/{path}",
    )

    output: list[str] = []

    for line in lines:
        if line.endswith("\n"):
            output.append(
                line,
            )

        else:
            output.append(
                f"{line}\n\\ No newline at end of file\n",
            )

    return "".join(
        output,
    )


def _lines(
    text: str,
) -> list[str]:
    """Split on "\\n" only, keeping endings.

    ``str.splitlines`` also splits on form feeds and Unicode separators,
    which produced spurious "No newline at end of file" markers.
    """

    parts = text.split(
        "\n",
    )

    lines = [
        f"{part}\n"
        for part in parts[:-1]
    ]

    if parts[-1]:
        lines.append(
            parts[-1],
        )

    return lines


class ProposalStore:
    """Persist proposals under a project's storage directory."""

    def __init__(
        self,
        repository_root: Path,
    ) -> None:
        self._root = repository_root.resolve()

        self._directory = (
            project_storage_directory(
                repository_root,
            )
            / _PROPOSALS_DIRECTORY
        )

        self._storage = FileSystemStorage(
            root_directory=project_storage_directory(
                repository_root,
            ),
        )

        self._storage.initialize()

    def save(
        self,
        proposal: EditProposal,
    ) -> None:
        data = proposal.model_dump(
            mode="json",
        )

        try:
            self._storage.write_json(
                self._path(
                    proposal.proposal_id,
                ),
                {
                    **data,
                    "signature": sign(
                        data,
                        "proposal",
                        self._root,
                    ),
                },
            )

        except StorageError as error:
            raise EditingError(
                "Failed to save the proposal.",
            ) from error

    def load(
        self,
        proposal_id: str,
    ) -> EditProposal:
        if not _PROPOSAL_ID_PATTERN.fullmatch(
            proposal_id,
        ):
            raise ProposalNotFoundError(
                "Proposal not found.",
            )

        try:
            data = self._storage.read_json(
                self._path(
                    proposal_id,
                ),
            )

        except StorageResourceNotFoundError as error:
            raise ProposalNotFoundError(
                "Proposal not found.",
            ) from error

        except StorageError as error:
            raise EditingError(
                "Failed to load the proposal.",
            ) from error

        # Only proposals this installation wrote (and signed) are used:
        # a repository can ship a .local_openclaw/proposals directory
        # whose stored contents differ from the diff they display.
        signature = data.pop(
            "signature",
            None,
        ) if isinstance(data, dict) else None

        if not verify(
            data,
            signature,
            "proposal",
            self._root,
        ):
            raise UntrustedStateError(
                "This proposal was not created by this RIP installation (for example, "
                "it came with a cloned repository), so it cannot be used.",
            )

        try:
            return EditProposal.model_validate(
                data,
            )

        except ValidationError as error:
            raise EditingError(
                "The stored proposal is unreadable.",
            ) from error

    def list(
        self,
        limit: int = 50,
    ) -> list[EditProposal]:
        """Return the newest proposals first."""

        if not self._directory.is_dir():
            return []

        proposals: list[EditProposal] = []

        for path in self._directory.glob(
            "*.json",
        ):
            try:
                proposals.append(
                    self.load(
                        path.stem,
                    ),
                )

            except EditingError:
                continue

        proposals.sort(
            key=lambda proposal: proposal.created_at,
            reverse=True,
        )

        return proposals[:limit]

    @staticmethod
    def _path(
        proposal_id: str,
    ) -> Path:
        return _PROPOSALS_DIRECTORY / f"{proposal_id}.json"
